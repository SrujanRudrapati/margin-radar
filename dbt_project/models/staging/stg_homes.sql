-- One row per offer. Dates cast to DATE; row-level contribution margin matches generator.metrics.
select
    home_id,
    segment,
    market,
    band,
    product,
    cast(offer_date as date) as offer_date,
    offer_price,
    model_valuation,
    spread_pct,
    reno_estimate_usd,
    outcome,
    cast(contract_date as date) as contract_date,
    cast(cancel_date as date) as cancel_date,
    cast(close_date as date) as close_date,
    fee_usd,
    cast(reno_complete_date as date) as reno_complete_date,
    reno_actual_usd,
    cast(list_date as date) as list_date,
    cast(first_buyer_offer_date as date) as first_buyer_offer_date,
    days_to_first_offer,
    showings,
    cast(resale_date as date) as resale_date,
    resale_price,
    hold_days,
    holding_cost_usd,
    selling_cost_usd,
    offer_price - fee_usd as cash_paid_usd,
    resale_price - (offer_price - fee_usd) - reno_actual_usd - holding_cost_usd - selling_cost_usd as cm_usd
from {{ source('raw', 'homes') }}
